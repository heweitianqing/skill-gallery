// URLs the page loads from other hosts, parsed from the unmodified index.html.
// Plain <a href> links are navigation, not resources, so they are not counted.
function externalRefs(html) {
  const refs = new Map();
  const add = (url, kind) => {
    const u = url.startsWith('//') ? `https:${url}` : url;
    let host;
    try {
      host = new URL(u).host;
    } catch {
      return;
    }
    if (!refs.has(u)) refs.set(u, { url: u, host, kind });
  };
  const tagRe = /<(link|script|img|source|iframe|video|audio|embed|object)\b([^>]*)>/gi;
  for (const [, tag, attrs] of html.matchAll(tagRe)) {
    const t = tag.toLowerCase();
    if (t === 'link') {
      const rel = (attrs.match(/\brel\s*=\s*["']?([^"'>]+)/i)?.[1] || '').toLowerCase();
      if (/\b(preconnect|dns-prefetch|canonical|alternate|author|me)\b/.test(rel)) continue;
    }
    for (const [, url] of attrs.matchAll(/\b(?:src|href|data|poster)\s*=\s*["']?\s*((?:https?:)?\/\/[^"'\s>]+)/gi)) add(url, t);
  }
  for (const [, url] of html.matchAll(/@import\s+(?:url\(\s*)?["']?((?:https?:)?\/\/[^"')\s;]+)/gi)) add(url, 'css-import');
  for (const [, url] of html.matchAll(/url\(\s*["']?((?:https?:)?\/\/[^"')\s]+)/gi)) add(url, 'css-url');
  for (const [, url] of html.matchAll(/\bimport\s*(?:[\w*{}\s,]+from\s*)?\(?\s*["'](https?:\/\/[^"']+)["']/g)) add(url, 'js-import');
  return [...refs.values()];
}

