  const code = (v) => (v == null || v === '' ? null : `<code>${esc(v)}</code>`);
  const st = cellStatus(c);
  add('Status', `${badge(st)}${Array.isArray(r.failure_reasons) && r.failure_reasons.length ? ` <span class="small">${esc(r.failure_reasons.join('; '))}</span>` : ''}`);
