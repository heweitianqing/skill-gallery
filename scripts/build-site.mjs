// Normalized skill info. Field priority: meta.yaml > source.json > research/candidates.json.
// The commit actually used by the runs (run.json skill.source_commit) is kept separately.
function loadSkill(name, candidates, cells) {
  const dir = path.join(REPO_ROOT, 'skills', name);
  let meta = {};
  const metaFile = ['meta.yaml', 'meta.yml'].map((f) => path.join(dir, f)).find((f) => fs.existsSync(f));
  if (metaFile) {
    try {
      meta = parseYaml(fs.readFileSync(metaFile, 'utf8')) || {};
      if (typeof meta !== 'object' || Array.isArray(meta)) throw new Error('top level is not a map');
    } catch (e) {
      warn(`skills/${name}/${path.basename(metaFile)}: not parsed (${e.message}); using fallbacks`);
      meta = {};
    }
  }
  const sourceJson = readJson(path.join(dir, 'source.json')) || {};
  const cand = candidates.find((c) => (meta.research_id && c.id === meta.research_id) || c.name === name || c.skill?.frontmatter_name === name) || null;
  const obj = (v) => (v && typeof v === 'object' && !Array.isArray(v) ? v : null);
  const src = obj(meta.upstream) || obj(meta.source) || {};
  const lic = obj(meta.license) || {};
  const install = obj(meta.install) || {};
  const usage = obj(meta.invoke) || obj(meta.usage) || {};
  const fetch = obj(meta.fetch) || {};

  const runSkills = [...cells.values()].filter((c) => c.variant === name && c.run?.skill).map((c) => c.run.skill);
  const runCommits = [...new Set(runSkills.map((s) => s.source_commit).filter(Boolean))];

  const info = {
    name,
    title: asText(pick(meta.title, meta.display_name)) || name,
    summary: asText(pick(meta.summary, meta.description)),
    summary_zh: asText(pick(meta.summary_zh, cand?.summary)),
    repo: safeUrl(pick(src.repo, src.url, typeof meta.source === 'string' ? meta.source : null, meta.repo, sourceJson.url, cand?.repo?.url, runSkills[0]?.source_url)),
    path: asText(pick(src.path, meta.path, sourceJson.path, cand?.skill?.path, runSkills[0]?.source_path)),
    commit: asText(pick(src.commit, meta.commit, meta.pinned_commit, sourceJson.commit, cand?.commit?.repo_head_sha, runCommits[0])),
    skill_md: safeUrl(pick(src.skill_md, cand?.skill?.skill_md_url_pinned)),
    run_commits: runCommits,
    license: asText(pick(lic.spdx, lic.name, typeof meta.license === 'string' ? meta.license : null, runSkills[0]?.license_spdx, cand?.license?.spdx)),
    license_url: safeUrl(pick(lic.url, lic.file, meta.license_url, cand?.license?.file_url_pinned)),
    copyright: asText(lic.copyright),
    // How the gallery got the files: "git" (clone at the pinned commit) or "npm-cli" (the skill's own generator).
    fetch: { method: asText(fetch.method) || 'git', package: asText(fetch.package), version: asText(fetch.version), output_path: obj(fetch.output_path) || {} },
    install_claude: asText(pick(install.claude_code, install.claude)),
    install_codex: asText(pick(install.codex)),
    usage_claude: asText(pick(usage.claude_code, usage.claude)),
    usage_codex: asText(pick(usage.codex)),
    notes: [meta.notes, meta.notes_zh].flatMap((n) => (Array.isArray(n) ? n : n ? [n] : [])).map(String),
    research_notes: [],
    from: metaFile ? path.relative(REPO_ROOT, metaFile) : Object.keys(sourceJson).length ? `skills/${name}/source.json` : cand ? 'research/candidates.json' : null,
    has_meta: Boolean(metaFile),
  };
  if (!metaFile && cand) {
    const plugin = cand.claude_code?.install_plugin;
    for (const [label, v] of [
      ['Claude Code plugin', Array.isArray(plugin) ? plugin.join('\n') : plugin],
      ['Claude Code', cand.claude_code?.gotcha],
      ['Codex', cand.codex?.notes],
    ]) {
      if (typeof v === 'string' && v.trim()) info.research_notes.push({ label, text: v });
    }
  }
  info.missing = ['summary', 'repo', 'path', 'commit', 'license', 'license_url', 'install_claude', 'install_codex', 'usage_claude', 'usage_codex'].filter((k) => !info[k]);
  return info;
}

