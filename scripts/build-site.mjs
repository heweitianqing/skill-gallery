function hostsSummary(refs, max = 2) {
  if (!refs.length) return 'none';
  const hosts = [...new Set(refs.map((r) => r.host))];
  return hosts.length > max ? `${hosts.slice(0, max).join(', ')} +${hosts.length - max}` : hosts.join(', ');
}

