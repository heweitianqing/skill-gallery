function loadPrompts(order) {
  const dir = path.join(REPO_ROOT, 'prompts');
  const prompts = new Map();
  for (const f of isDir(dir) ? fs.readdirSync(dir).filter((x) => x.endsWith('.md')).sort() : []) {
    const text = fs.readFileSync(path.join(dir, f), 'utf8');
    const m = text.match(/^---\n([\s\S]*?)\n---\n?/);
    let meta = {};
    if (m) {
      try {
        meta = parseYaml(m[1]) || {};
      } catch (e) {
        warn(`prompts/${f}: frontmatter not parsed (${e.message})`);
      }
    }
    const id = String(meta.id || f.replace(/\.md$/, ''));
    if (!SAFE_NAME.test(id)) {
      warn(`prompts/${f}: unusable id "${id}", skipped`);
      continue;
    }
    prompts.set(id, {
      id,
      title: meta.title ? String(meta.title) : id,
      version: meta.version ?? null,
      file: `prompts/${f}`,
      file_sha256: crypto.createHash('sha256').update(fs.readFileSync(path.join(dir, f))).digest('hex'),
      body: m ? text.slice(m[0].length).trim() : text.trim(),
    });
  }
  return sortByOrder(prompts, order);
}

function sortByOrder(map, order) {
  const keys = [...map.keys()].sort((a, b) => {
    const ia = order.indexOf(a);
    const ib = order.indexOf(b);
    if (ia !== -1 || ib !== -1) return (ia === -1 ? 1e9 : ia) - (ib === -1 ? 1e9 : ib);
    return a.localeCompare(b);
  });
  return new Map(keys.map((k) => [k, map.get(k)]));
}

function scanRuns(runsDir, agentIds) {
  const cells = new Map();
  if (!isDir(runsDir)) {
    warn(`no runs directory at ${runsDir}`);
    return cells;
  }
  for (const p of fs.readdirSync(runsDir).sort()) {
    const pd = path.join(runsDir, p);
    if (p.startsWith('.') || p.startsWith('_') || !isDir(pd)) continue;
    if (!SAFE_NAME.test(p)) {
      warn(`runs/${p}: unusable prompt directory name, skipped`);
      continue;
    }
    for (const name of fs.readdirSync(pd).sort()) {
      const cd = path.join(pd, name);
      if (name.startsWith('.') || name.startsWith('_') || !isDir(cd)) continue;
      const m = name.match(/^([a-z0-9]+)__([A-Za-z0-9][A-Za-z0-9._-]*)$/);
      if (!m) {
        warn(`runs/${p}/${name}: not an <agent>__<variant> directory, skipped`);
        continue;
      }
      if (!agentIds.includes(m[1])) {
        warn(`runs/${p}/${name}: unknown agent "${m[1]}", skipped`);
        continue;
      }
      const files = Object.fromEntries(CELL_FILES.map((f) => [f, fs.existsSync(path.join(cd, f))]));
      // An empty directory is a run that is still in progress.
      if (!Object.values(files).some(Boolean)) continue;
      let run = files['run.json'] ? readJson(path.join(cd, 'run.json'), `runs/${p}/${name}/run.json`) : null;
      if (run && (typeof run !== 'object' || Array.isArray(run))) run = null;
      const runInvalid = files['run.json'] && !run;
      cells.set(`${p}/${name}`, { prompt: p, agent: m[1], variant: m[2], name, dir: cd, files, run, runInvalid });
    }
  }
  return cells;
}

