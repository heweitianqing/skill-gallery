#!/usr/bin/env node
// Builds the static gallery site.
//
//   node scripts/build-site.mjs                  # writes site/dist/
//   node scripts/build-site.mjs --out <dir>      # write somewhere else
//   node scripts/build-site.mjs --runs <dir>     # read cells from another runs/ tree (testing)
//
// Inputs: runs/<prompt>/<agent>__<variant>/{index.html,desktop.png,mobile.png,run.json},
// prompts/*.md, skills/<name>/meta.yaml (falls back to skills/<name>/source.json and
// research/candidates.json), site/config.json and site/assets/.
//
// Cell files are copied into <out>/runs/ byte for byte. Thumbnails are cropped and
// scaled into <out>/thumbs/ with the small PNG codec below, so no dependencies are
// needed. Missing cells, files and fields render as "Pending" or "—"; they never
// fail the build.

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE_SRC = path.join(REPO_ROOT, 'site');
const CELL_FILES = ['index.html', 'desktop.png', 'mobile.png', 'run.json'];
const OUT_MARKER = '.skill-gallery-site';

const warnings = [];
const warn = (msg) => {
  warnings.push(msg);
  console.error(`warn: ${msg}`);
};

// ---------------------------------------------------------------- arguments

function parseArgs(argv) {
  const opts = { out: path.join(SITE_SRC, 'dist'), runs: path.join(REPO_ROOT, 'runs') };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--out' || a === '--runs') opts[a.slice(2)] = path.resolve(argv[++i] ?? '');
    else if (a === '-h' || a === '--help') {
      console.log('usage: node scripts/build-site.mjs [--out <dir>] [--runs <dir>]');
      process.exit(0);
    } else {
      console.error(`error: unknown argument ${a}`);
      process.exit(2);
    }
  }
  return opts;
}

// Refuse to wipe anything that is not a previous build of this site.
function prepareOutDir(out) {
  const rel = path.relative(out, REPO_ROOT);
  if (!rel || !rel.startsWith('..')) throw new Error(`refusing to use ${out} as output: it contains the repository`);
  if (fs.existsSync(out)) {
    const entries = fs.readdirSync(out);
    if (entries.length && !entries.includes(OUT_MARKER)) throw new Error(`refusing to overwrite ${out}: not empty and not a previous site build`);
    fs.rmSync(out, { recursive: true, force: true });
  }
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, OUT_MARKER), 'Generated by scripts/build-site.mjs. Safe to delete.\n');
  fs.writeFileSync(path.join(out, '.nojekyll'), '');
}

