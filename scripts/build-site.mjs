// Enough YAML for hand-written metadata files: nested maps, lists (of scalars or
// maps), quoted and plain scalars, flow lists, block scalars (| and >), comments.
function parseYaml(text) {
  const lines = text.replace(/\r\n?/g, '\n').replace(/\t/g, '  ').split('\n');
  let i = 0;
  const KEY = /^("(?:[^"\\]|\\.)*"|'(?:[^']|'')*'|[^\s:#'"-][^:]*?|-[^\s:][^:]*?)\s*:(?:\s+(.*)|)$/;
  const indentOf = (l) => l.match(/^ */)[0].length;
  const blank = (l) => /^\s*(#.*)?$/.test(l);
  const skipBlank = () => {
    while (i < lines.length && blank(lines[i])) i++;
  };
  const isItem = (t) => t === '-' || t.startsWith('- ');
  const fail = (msg) => {
    throw new Error(`line ${i + 1}: ${msg}`);
  };

  // Quotes only matter at the start of a scalar; an apostrophe inside plain text does not open one.
  function stripComment(s) {
    const t = s.trim();
    let from = 0;
    if (t[0] === '"' || t[0] === "'") {
      const re = t[0] === '"' ? /^"(?:[^"\\]|\\.)*"/ : /^'(?:[^']|'')*'/;
      from = t.match(re)?.[0].length ?? t.length;
    }
    for (let k = from; k < t.length; k++) {
      if (t[k] === '#' && (k === 0 || /\s/.test(t[k - 1]))) return t.slice(0, k).trimEnd();
    }
    return t;
  }

  function scalar(raw) {
    const s = stripComment(raw);
    if (s.startsWith('"')) {
      try {
        return JSON.parse(s);
      } catch {
        return s.slice(1, -1);
      }
    }
    if (s.startsWith("'")) return s.slice(1, -1).replace(/''/g, "'");
    if (s.startsWith('[') && s.endsWith(']')) {
      const inner = s.slice(1, -1).trim();
      return inner ? inner.split(',').map((x) => scalar(x.trim())) : [];
    }
    if (s === '' || s === '~' || s === 'null') return null;
    if (s === 'true') return true;
    if (s === 'false') return false;
    if (/^-?\d+(\.\d+)?$/.test(s) && !/^0\d/.test(s)) return Number(s);
    return s;
  }

  function blockScalar(header, parentIndent) {
    const fold = header[0] === '>';
    const strip = header.includes('-');
    const body = [];
    let contentIndent = null;
    while (i < lines.length) {
      const l = lines[i];
      if (l.trim() === '') {
        body.push('');
        i++;
        continue;
      }
      const ind = indentOf(l);
      if (ind <= parentIndent) break;
      if (contentIndent == null) contentIndent = ind;
      body.push(l.slice(Math.min(ind, contentIndent)));
      i++;
    }
    while (body.length && body[body.length - 1] === '') body.pop();
    let out = fold ? body.join('\n').replace(/([^\n])\n(?=[^\n])/g, '$1 ') : body.join('\n');
    if (!strip && out) out += '\n';
    return out;
  }

  function value(rest, indent) {
    const r = stripComment(rest ?? '');
    if (r === '') {
      skipBlank();
      if (i < lines.length) {
        const ind = indentOf(lines[i]);
        const t = lines[i].slice(ind);
        if (ind > indent || (ind === indent && isItem(t))) return block(ind);
      }
      return null;
    }
    if (/^[|>][+-]?\d*$/.test(r)) return blockScalar(r, indent);
    return scalar(rest);
  }

  function map(indent) {
    const obj = {};
    for (;;) {
      skipBlank();
      if (i >= lines.length) break;
      const ind = indentOf(lines[i]);
      if (ind < indent) break;
      if (ind > indent) fail('unexpected indentation');
      const t = lines[i].slice(ind);
      if (isItem(t)) break;
      const m = t.match(KEY);
      if (!m) fail('expected "key: value"');
      i++;
      obj[scalar(m[1])] = value(m[2], indent);
    }
    return obj;
  }

  function list(indent) {
    const arr = [];
    for (;;) {
      skipBlank();
      if (i >= lines.length) break;
      const l = lines[i];
      const ind = indentOf(l);
      if (ind !== indent || !isItem(l.slice(ind))) break;
      const after = l.slice(ind + 1);
      const rest = after.trimStart();
      const itemIndent = ind + 1 + (after.length - rest.length);
      if (rest === '' || rest.startsWith('#')) {
        i++;
        arr.push(value('', ind));
      } else if (!/^["'[]/.test(rest) && KEY.test(rest)) {
        lines[i] = ' '.repeat(itemIndent) + rest;
        arr.push(map(itemIndent));
      } else {
        i++;
        arr.push(/^[|>][+-]?\d*$/.test(stripComment(rest)) ? blockScalar(stripComment(rest), ind) : scalar(rest));
      }
    }
    return arr;
  }

  function block(indent) {
    skipBlank();
    if (i >= lines.length) return null;
    return isItem(lines[i].slice(indentOf(lines[i]))) ? list(indent) : map(indent);
  }

  if (lines[0]?.trim() === '---') i = 1;
  return block(0) ?? {};
}

// ---------------------------------------------------------------- PNG thumbnails

const PNG_SIG = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function readPngHeader(buf) {
  if (buf.length < 33 || !buf.subarray(0, 8).equals(PNG_SIG)) throw new Error('not a PNG file');
  let pos = 8;
  let ihdr = null;
  let plte = null;
  let trns = null;
  const idat = [];
  while (pos + 8 <= buf.length) {
    const len = buf.readUInt32BE(pos);
    const type = buf.toString('latin1', pos + 4, pos + 8);
    const data = buf.subarray(pos + 8, pos + 8 + len);
    if (type === 'IHDR') ihdr = { width: data.readUInt32BE(0), height: data.readUInt32BE(4), depth: data[8], color: data[9], interlace: data[12] };
    else if (type === 'PLTE') plte = data;
    else if (type === 'tRNS') trns = data;
    else if (type === 'IDAT') idat.push(data);
    else if (type === 'IEND') break;
    pos += 12 + len;
  }
  if (!ihdr) throw new Error('PNG without IHDR');
  const channels = { 0: 1, 2: 3, 3: 1, 4: 2, 6: 4 }[ihdr.color];
  if (ihdr.depth !== 8 || ihdr.interlace !== 0 || !channels) {
    throw new Error(`unsupported PNG (bit depth ${ihdr.depth}, color type ${ihdr.color}, interlace ${ihdr.interlace})`);
  }
  return { ...ihdr, channels, plte, trns, idat: Buffer.concat(idat) };
}

// Inflate only as much image data as the first `rows` rows need.
async function inflatePrefix(data, need) {
  const inflate = zlib.createInflate();
  inflate.end(data);
  const chunks = [];
  let got = 0;
  for await (const chunk of inflate) {
    chunks.push(chunk);
    got += chunk.length;
    if (got >= need) break;
  }
  return Buffer.concat(chunks);
}

// Decodes the top `rows` rows of an 8-bit PNG into RGB, composited over white.
async function decodePngTop(buf, rows) {
  const png = readPngHeader(buf);
  const h = Math.min(rows, png.height);
  const bpp = png.channels;
  const stride = png.width * bpp;
  const raw = await inflatePrefix(png.idat, h * (stride + 1));
  if (raw.length < h * (stride + 1)) throw new Error('truncated PNG data');
  const px = Buffer.alloc(stride * h);
  let prev = Buffer.alloc(stride);
  for (let y = 0; y < h; y++) {
    const filter = raw[y * (stride + 1)];
    const line = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    const cur = px.subarray(y * stride, (y + 1) * stride);
    for (let x = 0; x < stride; x++) {
      const a = x >= bpp ? cur[x - bpp] : 0;
      const b = prev[x];
      const c = x >= bpp ? prev[x - bpp] : 0;
      let v = line[x];
      if (filter === 1) v += a;
      else if (filter === 2) v += b;
      else if (filter === 3) v += (a + b) >> 1;
      else if (filter === 4) {
        const p = a + b - c;
        const pa = Math.abs(p - a);
        const pb = Math.abs(p - b);
        const pc = Math.abs(p - c);
        v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
      } else if (filter !== 0) throw new Error(`bad PNG filter ${filter}`);
      cur[x] = v & 255;
    }
    prev = cur;
  }
  const rgb = Buffer.alloc(png.width * h * 3);
  for (let p = 0, n = png.width * h; p < n; p++) {
    let r;
    let g;
    let b;
    let alpha = 255;
    const s = p * bpp;
    if (png.color === 2 || png.color === 6) {
      r = px[s];
      g = px[s + 1];
      b = px[s + 2];
      if (png.color === 6) alpha = px[s + 3];
    } else if (png.color === 0 || png.color === 4) {
      r = g = b = px[s];
      if (png.color === 4) alpha = px[s + 1];
    } else {
      const idx = px[s];
      r = png.plte?.[idx * 3] ?? 0;
      g = png.plte?.[idx * 3 + 1] ?? 0;
      b = png.plte?.[idx * 3 + 2] ?? 0;
      if (png.trns && idx < png.trns.length) alpha = png.trns[idx];
    }
    const o = p * 3;
    rgb[o] = (r * alpha + 255 * (255 - alpha)) / 255;
    rgb[o + 1] = (g * alpha + 255 * (255 - alpha)) / 255;
    rgb[o + 2] = (b * alpha + 255 * (255 - alpha)) / 255;
  }
  return { width: png.width, height: h, fullHeight: png.height, rgb };
}

// Area-average resample of the crop (0,0)-(cw,ch) of an RGB image to tw x th.
function resample(img, cw, ch, tw, th) {
  const out = Buffer.alloc(tw * th * 3);
  const sx = cw / tw;
  const sy = ch / th;
  for (let ty = 0; ty < th; ty++) {
    const y0 = Math.floor(ty * sy);
    const y1 = Math.max(y0 + 1, Math.min(ch, Math.floor((ty + 1) * sy)));
    for (let tx = 0; tx < tw; tx++) {
      const x0 = Math.floor(tx * sx);
      const x1 = Math.max(x0 + 1, Math.min(cw, Math.floor((tx + 1) * sx)));
      let r = 0;
      let g = 0;
      let b = 0;
      for (let y = y0; y < y1; y++) {
        for (let x = x0; x < x1; x++) {
          const i = (y * img.width + x) * 3;
          r += img.rgb[i];
          g += img.rgb[i + 1];
          b += img.rgb[i + 2];
        }
      }
      const n = (y1 - y0) * (x1 - x0);
      const o = (ty * tw + tx) * 3;
      out[o] = Math.round(r / n);
      out[o + 1] = Math.round(g / n);
      out[o + 2] = Math.round(b / n);
    }
  }
  return out;
}

function encodePng(rgb, w, h) {
  const stride = w * 3;
  const filtered = Buffer.alloc((stride + 1) * h);
  const cand = Array.from({ length: 5 }, () => Buffer.alloc(stride));
  for (let y = 0; y < h; y++) {
    const cur = rgb.subarray(y * stride, (y + 1) * stride);
    const prev = y ? rgb.subarray((y - 1) * stride, y * stride) : null;
    let best = 0;
    let bestSum = Infinity;
    for (let f = 0; f < 5; f++) {
      const o = cand[f];
      let sum = 0;
      for (let x = 0; x < stride; x++) {
        const a = x >= 3 ? cur[x - 3] : 0;
        const b = prev ? prev[x] : 0;
        const c = prev && x >= 3 ? prev[x - 3] : 0;
        let pred = 0;
        if (f === 1) pred = a;
        else if (f === 2) pred = b;
        else if (f === 3) pred = (a + b) >> 1;
        else if (f === 4) {
          const p = a + b - c;
          const pa = Math.abs(p - a);
          const pb = Math.abs(p - b);
          const pc = Math.abs(p - c);
          pred = pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
        }
        const v = (cur[x] - pred) & 255;
        o[x] = v;
        sum += v < 128 ? v : 256 - v;
      }
      if (sum < bestSum) {
        bestSum = sum;
        best = f;
      }
    }
    filtered[y * (stride + 1)] = best;
    cand[best].copy(filtered, y * (stride + 1) + 1);
  }
  const chunk = (type, data) => {
    const head = Buffer.alloc(8);
    head.writeUInt32BE(data.length, 0);
    head.write(type, 4, 'latin1');
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(crc32(Buffer.concat([head.subarray(4), data])), 0);
    return Buffer.concat([head, data, crc]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0);
  ihdr.writeUInt32BE(h, 4);
  ihdr[8] = 8;
  ihdr[9] = 2;
  return Buffer.concat([PNG_SIG, chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(filtered, { level: 9 })), chunk('IEND', Buffer.alloc(0))]);
}

// Crops the first screen of a full-page screenshot and writes scaled copies.
// `aspect` is crop height / width; each target is { file, width }.
async function writeThumbs(src, viewportWidth, aspect, targets) {
  const buf = fs.readFileSync(src);
  const { width } = readPngHeader(buf);
  const cw = Math.min(width, viewportWidth || width);
  const img = await decodePngTop(buf, Math.round(cw * aspect));
  const ch = img.height;
  for (const t of targets) {
    const tw = Math.min(t.width, cw);
    const th = Math.max(1, Math.round((ch * tw) / cw));
    fs.mkdirSync(path.dirname(t.file), { recursive: true });
    fs.writeFileSync(t.file, encodePng(resample(img, cw, ch, tw, th), tw, th));
  }
  return { width, fullHeight: img.fullHeight };
}

